#!/usr/bin/env node
// Builds the "Open entries to send to Frax" section at the bottom of docs/UNCERTAINTIES.md from the entries above it.
//   node scripts/uncertainties.mjs --write   rewrite the section
//   node scripts/uncertainties.mjs --check   exit 1 if the section is missing or out of date (CI)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const FILE = fileURLToPath(new URL("../docs/UNCERTAINTIES.md", import.meta.url));
const HEADING = "## Open entries to send to Frax";
const STOP = "## Not for Frax";

function openEntries(text) {
  const body = text.slice(0, text.indexOf(STOP));
  const groups = [];
  for (const chunk of body.split(/^## /m).slice(1)) {
    const section = chunk.slice(0, chunk.indexOf("\n")).trim();
    const entries = [];
    for (const match of chunk.matchAll(/^### (U-\d+): (.+)\n([\s\S]*?)(?=^### |^---|(?![\s\S]))/gm)) {
      const [, id, title, rest] = match;
      const status = /\*\*Status:\*\*\s*(.+)/.exec(rest)?.[1].trim();
      if (status !== "open") continue;
      const ask = /\*\*What we need from Frax:\*\*\s*(.+)/.exec(rest)?.[1].trim() ?? "";
      entries.push({ id, title: title.trim(), ask });
    }
    if (entries.length) groups.push({ section, entries });
  }
  return groups;
}

function render(groups) {
  const all = groups.flatMap((g) => g.entries);
  // "Nothing." entries are listed by ID only; one that still asks something ("Is that fine?", "unless ...") stays in
  const noReply = all.filter((e) => /^Nothing\b/.test(e.ask) && !e.ask.includes("?") && !/\bunless\b/.test(e.ask));
  const lines = [
    HEADING,
    "",
    `Generated by \`node scripts/uncertainties.mjs --write\` from the entries above, and CI fails if it drifts. ${all.length} entries are open. Paste everything below the line into one message to Frax. A-01 goes to ASUC, not Frax.`,
    "",
    "---",
    "",
    "These are the calls B@B made building the college org financing MVP that we'd like Frax to confirm or change. Each has an ID from docs/UNCERTAINTIES.md so replies can point at it, and the full entry there has what we built, the alternative, and the cost to change.",
  ];
  for (const { section, entries } of groups) {
    const asks = entries.filter((e) => !noReply.includes(e));
    if (!asks.length) continue;
    lines.push("", `### ${section}`, "");
    for (const e of asks) lines.push(`- ${e.id} ${e.title}`, `  ${e.ask}`);
  }
  if (noReply.length) {
    lines.push("", "### For the record, no reply needed", "", noReply.map((e) => e.id).join(", "));
  }
  return `${lines.join("\n")}\n`;
}

const text = readFileSync(FILE, "utf8");
const start = text.indexOf(HEADING);
const current = start === -1 ? "" : text.slice(start);
const next = render(openEntries(text));

if (process.argv.includes("--write")) {
  const base = start === -1 ? `${text.trimEnd()}\n\n---\n\n` : text.slice(0, start);
  writeFileSync(FILE, base + next);
  console.log(`wrote ${HEADING.slice(3)}: ${openEntries(text).flatMap((g) => g.entries).length} open entries`);
} else if (process.argv.includes("--check")) {
  if (current !== next) {
    console.error(`docs/UNCERTAINTIES.md: "${HEADING.slice(3)}" is out of date. Run node scripts/uncertainties.mjs --write`);
    process.exit(1);
  }
  console.log("open entries section is current");
} else {
  process.stdout.write(next);
}
